def install_E(sy, E_cell):
    """Write a per-cell Young's modulus into the particles so the WARM-UP uses it too."""
    p = sy.p
    y = E_cell[sy.cid]
    p.youngs = y
    p.mu, p.la = _lame(y)


def build_planted(args, warmup, log, seed=2026):
    """A system whose trajectory was generated by a PLANTED (E, gain), with x_{k-1} recorded."""
    sy = System(device=args.device, n_cells=args.cells, per_parent=args.per_parent,
                n_grid=args.n_grid, warmup=0, dtype=args.dtype, mode=args.mode,
                real=args.real, wall_damp=args.wall_damp)
    C = sy.C
    g = torch.Generator().manual_seed(seed)
    E = (args.e_lo + (args.e_hi - args.e_lo) * torch.rand(C, generator=g)).to(sy.device, sy.dtype)
    gn = (args.g_lo + (args.g_hi - args.g_lo) * torch.rand(C, generator=g)).to(sy.device, sy.dtype)
    sy.E_planted_source = "U(%g,%g)" % (args.e_lo, args.e_hi)
    sy.E_true[1:] = E
    sy.gain_true[1:] = gn
    sy.theta_true = torch.cat([sy.E_true[1:], sy.gain_true[1:]])
    install_E(sy, sy.E_true)

    # --- warm up on the planted theta, capturing the position one substep before the snapshot ---
    x_prev = None
    for tick in range(warmup):
        sy._outer(tick, gain_cell=sy.gain_true)
        sy.H.sub_dt = sy.dt_sub
        for s in range(sy.n_sub_per_frame):
            if tick == warmup - 1 and s == sy.n_sub_per_frame - 1:
                x_prev = sy.p.get("pos").clone()
            for tok in SUBSTEP_TOKENS:
                sy._tok(tok)
        sy.H.sub_dt = None
    # also the position one FULL FRAME before the snapshot (for the frame-cadence variant)
    sy.warmup_frames = warmup
    sy._snapshot(warmup)
    sy.x_prev = x_prev
    log(f"[planted] C={sy.C} cells, Np={sy.Np}, grid {sy.g.nx}^2, dtype={sy.dtype}, "
        f"warmup={warmup} frames, dt={sy.dt} dt_sub={sy.dt_sub} ({sy.n_sub_per_frame}/frame)")
    log(f"          E planted in [{float(E.min()):.1f}, {float(E.max()):.1f}]  "
        f"gain planted in [{float(gn.min()):.3f}, {float(gn.max()):.3f}]  dx={sy.g.dx:.6g}")
    return sy


def frame_prev(args, warmup, log, seed=2026):
    """Re-run the same planted system one FRAME short, to get x at frame k-1 (frame cadence)."""
    sy = build_planted(args, warmup - 1, log=lambda *a: None, seed=seed)
    x = sy.p.get("pos").clone()
    del sy
    torch.cuda.empty_cache()
    return x


