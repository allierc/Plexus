def theta_scale(C, device, e_ref=130.0, g_ref=1.0):
    """NOMINAL column scaling (not the truth -- using theta_true here would be cheating)."""
    s = torch.ones(2 * C, device=device, dtype=torch.float64)
    s[:C] = e_ref
    s[C:] = g_ref
    return s


class Solver:
    """Normal equations for a FIXED A, at several ridge levels + a truncated pseudo-inverse.

    Column-scaled by a NOMINAL theta scale (E_ref=130, gain_ref=1) so that ridge and the rcond
    truncation mean the same thing for both blocks. Using theta_true to scale would be cheating.
    """

    LAMS = (0.0, 1e-12, 1e-10, 1e-8, 1e-6, 1e-4, 1e-2)
    RCONDS = (1e-12, 1e-10, 1e-8, 1e-6)

    def __init__(self, A, C):
        self.C = C
        self.s = theta_scale(C, A.device)
        self.Az = A.double() * self.s[None, :]
        G = self.Az.T @ self.Az
        n = G.shape[0]
        self.tr = float(torch.diagonal(G).sum() / n)
        self.I = torch.eye(n, device=G.device, dtype=torch.float64)
        self.G = G
        ev, U = torch.linalg.eigh(G)
        self.ev, self.U = ev.clamp(min=0), U
        self.cond = float(self.ev.max() / self.ev.clamp(min=1e-300).min())
        self.fac = {}
        for lam in self.LAMS:
            M = G + lam * self.tr * self.I
            try:
                L = torch.linalg.cholesky(M)
                if not torch.isfinite(L).all():
                    raise RuntimeError
                self.fac[lam] = ("chol", L)
            except Exception:                     # G is not numerically PD at lam = 0
                self.fac[lam] = ("lu", torch.linalg.lu_factor(M))

    def __call__(self, b):
        rhs = self.Az.T @ b.double()
        out = {}
        for lam in self.LAMS:
            kind, F = self.fac[lam]
            if kind == "chol":
                z = torch.cholesky_solve(rhs.unsqueeze(1), F).squeeze(1)
            else:
                z = torch.linalg.lu_solve(F[0], F[1], rhs.unsqueeze(1)).squeeze(1)
            out[f"ridge{lam:g}"] = z * self.s
        Utr = self.U.T @ rhs
        for rc in self.RCONDS:
            keep = self.ev > self.ev.max() * rc
            zi = torch.where(keep, 1.0 / self.ev.clamp(min=1e-300), torch.zeros_like(self.ev))
            out[f"pinv{rc:g}"] = (self.U @ (zi * Utr)) * self.s
        return out

    def ranks(self):
        return {f"pinv{rc:g}": int((self.ev > self.ev.max() * rc).sum()) for rc in self.RCONDS}

    def free(self):
        del self.Az
        torch.cuda.empty_cache()


def score(theta_hat, theta_true, C):
    e = ((theta_hat - theta_true) / theta_true).abs()
    eE, eg = e[:C], e[C:]
    q = lambda t, p: float(torch.quantile(t, p))
    return {"med_E": q(eE, 0.5), "p90_E": q(eE, 0.9), "max_E": float(eE.max()),
            "med_gain": q(eg, 0.5), "p90_gain": q(eg, 0.9), "max_gain": float(eg.max()),
            "rel_l2": float((theta_hat - theta_true).norm() / theta_true.norm())}


