def noisy_positions(x_prev, x_k, x_next, sigma, gen):
    def n(x):
        return x + sigma * torch.randn(x.shape, generator=gen, device=x.device, dtype=x.dtype)
    return n(x_prev), n(x_k), n(x_next)


def fd_accel(x_prev, x_k, x_next, dt):
    return ((x_next - 2.0 * x_k + x_prev) / (dt * dt)).reshape(-1)


def set_state(sy, x, v, tick):
    """Write observed pos/vel into the frozen state and REFRESH the frozen body force."""
    p = sy.p
    pa, pb = p.state_schema["pos"]
    va, vb = p.state_schema["vel"]
    st = sy.state0.clone()
    st[:, pa:pb] = x
    st[:, va:vb] = v
    p.state = st
    p.F, p.C, p.Jp = sy.F0.clone(), sy.C0.clone(), sy.Jp0.clone()
    sy.state0 = p.state.clone()
    sy.x0, sy.v0 = x.clone(), v.clone()
    sy.act0, sy.pass0 = sy._outer(tick, gain_cell=None)
    sy.p.state = sy.state0.clone()          # _outer does not advect, but be explicit


