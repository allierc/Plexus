"""recover.py -- TASK D: PLANTED RECOVERY.

Plant known per-cell (E, gain), run the simulation with them, INJECT the resulting particle
positions, assemble A and b, and try to get the parameters back by least squares.

WHAT "INJECT THE POSITIONS" MEANS HERE, EXACTLY
====================================================================================================
The gather advects  x_{k+1} = x_k + dt_sub * v_{k+1}  and stores  v_{k+1}.  So, with no clamp,

    v_k    = (x_k - x_{k-1}) / dt_sub
    a_k    = (v_{k+1} - v_k) / dt_sub  =  (x_{k+1} - 2 x_k + x_{k-1}) / dt_sub^2

i.e. the acceleration that the algebraic constraint  A theta = b  is written against is a SECOND
DIFFERENCE of observed positions. That is the whole point of the task: the estimator differentiates
the data twice, and dt_sub = 2e-4, so the divisor is 4e-8. Every position error is multiplied by
2.4e7 before it reaches b. This script measures that.

Three levels of honesty, all reported:

  ORACLE   b := a(theta_true) - a(0) straight out of the solver's velocities   (task C's b)
  FD       b := (x_{k+1} - 2 x_k + x_{k-1}) / dt_sub^2  - a(0), positions only (must equal ORACLE)
  N1       FD with Gaussian noise on the three position frames; A and a(0) still built from the
           CLEAN state -- the most optimistic possible noise model
  N2       the same noise ALSO written into the state that A and a(0) are built from: positions
           (p2g weights, wall masks, the activation sample) and velocity v_k = (x_k-x_{k-1})/dt_sub
           (hence drag). F and C stay at the solver's values -- they are not observable at all
           (task B blocker (a)), so N2 is still optimistic, just less so.

Only file created by this task: this one, plus recover_*.json / recover_*.png beside it.

usage:
  PYTHONPATH=/workspace/Plexus/src python recover.py --device cuda:1 --cells 100 --per-parent 100
  PYTHONPATH=/workspace/Plexus/src python recover.py --device cuda:1 --real --frame-cadence
"""
