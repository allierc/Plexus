def _patch4(path, block, rendered=False):
    """The shapes row, straight after the second-field row it extends."""
    if rendered:
        block = block.replace("&#x27;", "'")
    s = open(path).read()
    _b = _find_block(s, "vertex-turing-shapes")
    if _b and (not _find_block(s, "vertex-turing-second-field")
               or _b[0] < _find_block(s, "vertex-turing-second-field")[0]):
        i, j = _b
        s = s[:i] + block + s[j:]
        what = "replaced"
    else:
        _b = _find_block(s, "vertex-turing-shapes")
        if _b:                               # it exists, but after the row it should precede
            i, j = _b
            s = s[:i].rstrip("\n") + "\n" + s[j:].lstrip("\n")
        if BEGIN2 not in s:
            sys.exit(f"second-field marker not found in {path}")
        k = s.index(BEGIN2)
        s = s[:k] + block + "\n\n" + s[k:]
        what = "inserted"
    open(path, "w").write(s)
    print(f"[minisite] {os.path.relpath(path, ROOT)}: Vertex + Turing shapes row {what}")


