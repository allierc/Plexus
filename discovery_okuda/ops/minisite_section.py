def _patch(path, block, rendered=False):
    if rendered:
        block = block.replace("<h3>", '<h3 class="anchored">').replace("&#x27;", "'")
    s = open(path).read()
    anchor_old = ANCHOR_OLD if not rendered else ANCHOR_OLD.replace("<h3>", '<h3 class="anchored">')
    anchor_new = ANCHOR_NEW if not rendered else ANCHOR_NEW.replace("<h3>", '<h3 class="anchored">')
    _b = _find_block(s, "vertex-mpm")
    if _b:
        i, j = _b
        s = s[:i] + block + s[j:]
        what = "replaced"
    else:
        # AFTER THE MLS-MPM SECTION, not after Vertex + Turing: the interface is read once the
        # solver it couples to has been introduced. A section is placed after another by finding
        # the NEXT h3 -- a section ends where the following one begins, and inserting straight
        # after a heading would land inside that section's own prose.
        anchor = MPM_SECTION if not rendered else MPM_SECTION.replace("<h3>", '<h3 class="anchored">')
        if anchor not in s:
            sys.exit(f"the MLS-MPM heading was not found in {path}")
        k = s.index(anchor)
        tag = "<h3" if rendered else "<h3>"
        nxt = s.find(tag, k + len(anchor))
        nxt = len(s) if nxt < 0 else nxt
        s = s[:nxt] + block + "\n\n" + s[nxt:]
        what = "inserted"
    s = s.replace(anchor_old, anchor_new)
    open(path, "w").write(s)
    print(f"[minisite] {os.path.relpath(path, ROOT)}: {what}; heading renamed to 'Vertex + Turing'")


def _patch2(path, block, rendered=False):
    """The Vertex + Turing second row, inserted BETWEEN that section and the Vertex + MPM one.

    Anchored on the `BEGIN` marker of the Vertex + MPM block rather than on a heading, because it
    belongs to the section ABOVE that marker and has no heading of its own -- and because the two
    blocks then cannot be inserted in the wrong order however many times this runs.
    """
    if rendered:
        block = block.replace("&#x27;", "'")
    s = open(path).read()
    if BEGIN2_OLD in s:                       # one-time: drop the block under its former name
        a, b = s.index(BEGIN2_OLD), s.index(END2_OLD) + len(END2_OLD)
        s = s[:a] + s[b:]
        open(path, "w").write(s)
        print(f"[minisite] {os.path.relpath(path, ROOT)}: legacy 'vertex-turing-death' block removed")
    _b = _find_block(s, "vertex-turing-second-field")
    if _b:
        i, j = _b
        s = s[:i] + block + s[j:]
        what = "replaced"
    else:
        if BEGIN not in s:
            sys.exit(f"vertex-mpm marker not found in {path} -- run the first patch before this one")
        k = s.index(BEGIN)
        s = s[:k] + block + "\n\n" + s[k:]
        what = "inserted"
    open(path, "w").write(s)
    print(f"[minisite] {os.path.relpath(path, ROOT)}: Vertex + Turing second-field row {what}")


