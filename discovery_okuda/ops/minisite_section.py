def _run_dir(name, need=()):
    """A run's directory, live or archived, preferring one that HOLDS the files `need` names.

    Rounds 1-22 were moved into `log/okuda/_archive_r001-r022_<date>/` on 12 August, which is why
    two rows of the Vertex + Turing section quietly stopped rebuilding: the runs had not been
    deleted, they had been filed. Their artefacts -- `traj.npz`, `diag.json`, the `vtk_*` clips --
    moved with them, so a card only needs to know where to look.

    `need` exists because the discovery loop RE-USES slot names: a fresh `r013_05` appears in
    `log/okuda/` for a different simulation, carrying no `vtk_*` clips, and taking it on name
    alone dropped four cards off the page at once. When `need` is given, the first candidate
    holding all of it wins -- live, then archives newest-named first -- so the card keeps both
    the clip and the `spec_run.yaml` of the run the clip was rendered from, not a namesake's.
    """
    import glob as _glob
    live = os.path.join(LOG_OKUDA, name)
    cands = ([live] if os.path.isdir(live) else []) + \
        sorted(_glob.glob(os.path.join(LOG_OKUDA, "_archive_*", name)), reverse=True)
    for c in cands:
        if all(os.path.exists(os.path.join(c, f)) for f in need):
            return c
    return cands[0] if cands else live


def _find_block(s, name):
    """(start, end) of the block called `name`, whatever path its marker names -- or None.

    Matched on the NAME alone: the generator's own path used to be part of the marker string, so
    moving this file made every block on the page unrecognisable and each run appended another
    copy of it. Fourteen copies of one section is what that cost.
    """
    m = re.search(r"<!-- BEGIN " + re.escape(name) + r" \(generated by [^)]*\) -->", s)
    if not m:
        return None
    e = s.find(f"<!-- END {name} -->", m.end())
    if e < 0:
        return None
    return m.start(), e + len(f"<!-- END {name} -->")


def _content_box(src, x0, wid, hei, n=9, thresh=14, skip_top=0.0, skip_bot=0.0, y0=0):
    """The bounding box of everything that is not background, in a REGION of the frame.

    Both panels of these movies are drawn on black with matplotlib's own margins around them, and
    the margins are not symmetric -- the 3D axes sit left of centre and the 2D section right of it,
    which is exactly what a viewer sees as "the first half is a bit to the left and the second a bit
    to the right". Centring is therefore a property of the CONTENT, not of the frame, and it has to
    be measured rather than nudged.

    Sampled over `n` frames and unioned, because the content MOVES: a box measured on one frame
    crops away the part of the run that happens later. Threshold on the max channel, so a dim strand
    counts as content and JPEG-ish ringing around the border does not.
    """
    import glob
    import tempfile
    import numpy as _np
    import matplotlib.image as _mpimg
    d = tempfile.mkdtemp(prefix="mscrop_")
    subprocess.check_call([_exe("ffmpeg"), "-y", "-loglevel", "error", "-i", src,
                           "-vf", "select='not(mod(n\\," + str(max(1, _nframes(src) // n))
                           + "))'",
                           "-vsync", "vfr", os.path.join(d, "f%03d.png")])
    xs0, xs1, ys0, ys1 = wid, 0, hei, 0
    for f in sorted(glob.glob(os.path.join(d, "*.png"))):
        a = _mpimg.imread(f)
        # `y0` as well as `x0`, because a panel is not always in the top row: the four-panel
        # proteolysis movie has two, and a box measured from row 0 for a bottom-row panel is a box
        # around the panel above it.
        a = (a[:, :, :3].max(axis=2)
             * (255 if a.dtype.kind == "f" else 1))[y0:y0 + hei, x0:x0 + wid]
        # THE PRINTED LABEL IS NOT CONTENT. Every one of these movies stamps the run name, the frame
        # and the cell count in the top-left corner, in white on black -- so a bounding box that
        # measures brightness puts the box around the TEXT as well as around the tissue, and the
        # crop that follows keeps the text and shrinks the subject. `skip_top` is the fraction of
        # the panel the label occupies; measured below it, the box is the tissue's.
        if skip_top:
            a = a[int(skip_top * hei):]
        # AND THE SCALE BAR IS NOT CONTENT EITHER. The okuda movies draw a white rule and its length
        # in the bottom margin of every panel; a box that includes it is a box around the bar, and
        # the square crop that follows then keeps the bar and shrinks the tissue.
        if skip_bot:
            a = a[:max(1, a.shape[0] - int(skip_bot * hei))]
        m = a > thresh
        if not m.any():
            continue
        cols, rows = _np.nonzero(m.any(0))[0], _np.nonzero(m.any(1))[0]
        xs0, xs1 = min(xs0, int(cols[0])), max(xs1, int(cols[-1]))
        ys0, ys1 = min(ys0, int(rows[0])), max(ys1, int(rows[-1]))
    import shutil as _sh
    _sh.rmtree(d, ignore_errors=True)
    if xs1 <= xs0 or ys1 <= ys0:
        return wid // 2, hei // 2, min(wid, hei)
    return (xs0 + xs1) // 2, (ys0 + ys1) // 2, max(xs1 - xs0, ys1 - ys0)


def _nframes(src):
    out = subprocess.check_output([_exe("ffprobe"), "-v", "error", "-select_streams", "v",
                                   "-count_frames", "-show_entries", "stream=nb_read_frames",
                                   "-of", "csv=p=0", src]).decode().strip()
    return max(1, int(out.split(",")[0]))


def split_concat(src, dst, recentre=True, skip_top=0.0):
    """Cut the two-panel movie in half and play the halves in SEQUENCE: 3D first, then the section.

    ONE CLIP PER RUN, NOT TWO. A gallery card is a square block, and the movie is 2:1 -- shown whole it
    letterboxes to a third of the card's height and neither panel is legible. Two cards per run would fit
    but would spend six of the row's slots on three runs, and the confinement SERIES is the thing the row
    exists to show. Concatenating in time gives one square card per run that shows both views.

    CUT, NOT RE-RENDERED. The halves are the same pixels the movie has, so the page cannot end up
    disagreeing with the artefact it was made from.
    """
    ff = _exe("ffmpeg")
    w, h = _size(src)
    half = (w // 2) - (w // 2) % 2
    ax, ay, aw = 0, 0, half
    bx, by, bw = w - half, 0, half
    side = h
    if recentre:
        # EACH HALF CENTRED ON ITS OWN CONTENT, and both cropped to ONE size, because `concat`
        # requires it. The window is the larger of the two contents plus a fifth, so neither panel
        # is cut and the smaller one is not blown up past the other.
        cxa, cya, sa = _content_box(src, 0, half, h, skip_top=skip_top)
        cxb, cyb, sb = _content_box(src, w - half, half, h, skip_top=skip_top)
        cya += int(skip_top * h); cyb += int(skip_top * h)      # back into full-frame rows
        side = min(h, half, int(1.2 * max(sa, sb)))
        side -= side % 2
        ax = min(max(cxa - side // 2, 0), half - side)
        ay = min(max(cya - side // 2, 0), h - side)
        bx = (w - half) + min(max(cxb - side // 2, 0), half - side)
        by = min(max(cyb - side // 2, 0), h - side)
        aw = bw = side
        print(f"[minisite]   recentred: {side}x{side} windows at ({ax},{ay}) and ({bx},{by}) "
              f"of {w}x{h}", flush=True)
    cmd = [ff, "-y", "-loglevel", "error", "-i", src, "-filter_complex",
           f"[0:v]crop={aw}:{side}:{ax}:{ay}[a];[0:v]crop={bw}:{side}:{bx}:{by}[b];"
           f"[a][b]concat=n=2:v=1[o]",
           "-map", "[o]", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "21", dst]
    if subprocess.call(cmd) != 0 or not os.path.exists(dst):
        sys.exit(f"ffmpeg split+concat failed for {dst}")



def panels_concat(src, dst, panels, skip_top=0.0, skip_bot=0.0, pad=1.16, side=460):
    """Cut a grid movie into named panels and play them in SEQUENCE, each square on its own content.

    A GRID DOES NOT SURVIVE A GALLERY CARD. These runs are drawn to be READ -- three or four views
    of the same frame side by side, at a size that suits a page -- and a card is one square block,
    so the whole grid arrives at a third or a quarter of its linear size and the fibres, which are
    one pixel wide to begin with, arrive at none. Played one after another, each panel gets the
    whole card.

    `panels` is a list of (x0, y0, w, h) in FRACTIONS of the frame, in the order they should play.
    Each is cropped to a square window centred on what is drawn INSIDE it -- panels of these movies
    are not filled evenly, and one of 04d's three is a sphere in the corner of its quadrant with an
    inset beside it -- and all the windows are then made the same size, because `concat` requires
    it. The window is the largest content plus `pad`, so the smallest panel is not blown up to fill
    a card the others earned.
    """
    ff = _exe("ffmpeg")
    w, h = _size(src)
    boxes = []
    for (fx, fy, fw, fh) in panels:
        x0, y0 = int(fx * w), int(fy * h)
        pw, ph = int(fw * w), int(fh * h)
        cx, cy, sz = _content_box(src, x0, pw, ph, y0=y0, skip_top=skip_top, skip_bot=skip_bot)
        boxes.append((x0, y0, pw, ph, x0 + cx, y0 + int(skip_top * ph) + cy, sz))
    # THE MARGINS BIND THE WINDOW, NOT ONLY THE MEASUREMENT. Skipping the text while measuring puts
    # the box around the right thing and then the square window, being larger, reaches back over the
    # label anyway -- which is how the first cut of 04d came out with the run name still burnt into
    # its first sequence. The window is capped at the panel MINUS both margins and clamped between
    # them, so a printed label cannot re-enter through the padding.
    tpx = int(skip_top * min(b[3] for b in boxes))
    bpx = int(skip_bot * min(b[3] for b in boxes))
    side = min(min(b[2] for b in boxes), min(b[3] for b in boxes) - tpx - bpx,
               int(pad * max(b[6] for b in boxes)))
    side -= side % 2
    parts, labels = [], []
    for n, (x0, y0, pw, ph, cx, cy, _sz) in enumerate(boxes):
        x = min(max(cx - side // 2, x0), x0 + pw - side)
        y = min(max(cy - side // 2, y0 + tpx), y0 + ph - bpx - side)
        x, y = max(0, min(x, w - side)), max(0, min(y, h - side))
        parts.append(f"[0:v]crop={side}:{side}:{x}:{y}[p{n}]")
        labels.append(f"[p{n}]")
        print(f"[minisite]   panel {n}: {side}x{side} at ({x},{y}) of {w}x{h}", flush=True)
    fc = ";".join(parts) + ";" + "".join(labels) + f"concat=n={len(boxes)}:v=1[o]"
    # SCALED TO THE PAGE'S OWN SIZE. The VTK sources are 1,568 px square; concatenating four of
    # their quadrants unscaled put a single card at 17.8 MB, which is more than the rest of the
    # gallery put together.
    fc = fc.replace("[o]", "[c]") + f";[c]scale={side}:{side}:flags=lanczos[o]"
    cmd = [ff, "-y", "-loglevel", "error", "-i", src, "-filter_complex", fc,
           "-map", "[o]", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "24",
           "-movflags", "+faststart", dst]
    if subprocess.call(cmd) != 0 or not os.path.exists(dst):
        sys.exit(f"ffmpeg panels+concat failed for {dst}")


def vtk_sequence(run_dir, dst, side=460, kb_seconds=5.0, crop=24, kinds=("evolve", "kburns")):
    """The VTK sequence as one clip: without the mesh, then with it, each grown then turned.

    FOUR MOVEMENTS, ONE CARD. `vtk_render --seq 3` writes evolve/kburns x nomesh/mesh. Played in
    that order the card answers both questions a shape raises -- what it did (time moves, camera
    still) and what it is (camera moves, time still) -- first as a surface and then as cells.

    THE ROTATION IS RETIMED AND THE GROWTH IS NOT. Four clips at their own pace are 46 s, twice
    what any other card on the page runs; and of the four, the two turns are the redundant pair --
    the same revolution twice, once per style. Compressing those to `kb_seconds` each and leaving
    the growth alone puts the card at 20 s without touching the part that only happens once.

    THE LABEL IS CROPPED, not disabled: `vtk_render` stamps "<run> <style>" in the top-left, rows
    5-20 of an 896 px frame, and the page writes its own captions. `crop` is taken off all four
    sides so the frame stays square; at full zoom that costs the tissue about 3% of its height,
    which is the price of not having a run name burnt into a gallery card.
    """
    ff = _exe("ffmpeg")
    # `kinds` drops a movement for the runs that do not need it: a turntable earns its place on a
    # shape with arms pointing at the lens, and adds nothing to a sphere that shrinks.
    parts = [(k, st) for st in ("nomesh", "mesh") for k in ("evolve", "kburns") if k in kinds]
    srcs = [os.path.join(run_dir, f"vtk_{k}_{st}.mp4") for k, st in parts]
    missing = [os.path.basename(p) for p in srcs if not os.path.exists(p)]
    if missing:
        print(f"[minisite] {os.path.basename(run_dir)}: missing {missing} -- clip not rebuilt")
        return False
    w, h = _size(srcs[0])
    c = min(crop, (min(w, h) - 2) // 2)
    fc, labels = [], []
    for n, ((kind, _st), src) in enumerate(zip(parts, srcs)):
        # `setpts` before `fps`: retime first, then resample, or the frames are dropped at the old
        # rate and the clip stutters.
        rt = ""
        if kind == "kburns":
            dur = float(subprocess.check_output(
                [_exe("ffprobe"), "-v", "error", "-show_entries", "format=duration",
                 "-of", "csv=p=0", src]).decode().strip())
            rt = f"setpts={kb_seconds / dur:.5f}*PTS,"
        fc.append(f"[{n}:v]crop={w - 2 * c}:{h - 2 * c}:{c}:{c},{rt}fps=25,"
                  f"scale={side}:{side}:flags=lanczos,setsar=1[v{n}]")
        labels.append(f"[v{n}]")
    cmd = [ff, "-y", "-loglevel", "error"]
    for src in srcs:
        cmd += ["-i", src]
    cmd += ["-filter_complex",
            ";".join(fc) + ";" + "".join(labels) + f"concat=n={len(parts)}:v=1[o]",
            "-map", "[o]", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "26",
            "-movflags", "+faststart", dst]
    if subprocess.call(cmd) != 0 or not os.path.exists(dst):
        sys.exit(f"ffmpeg vtk sequence failed for {dst}")
    print(f"[minisite]   {os.path.basename(run_dir)}: {len(parts)} VTK clips -> {side}x{side}, "
          f"{_nframes(dst)} frames")
    return True


def evolve_then_kburns(run_dir, dst, panel="left", pad=1.26, skip_top=0.09, skip_bot=0.14):
    """The run through time, then the finished specimen turned on the spot -- one clip.

    TWO MOVIES THAT ANSWER DIFFERENT QUESTIONS. `movie.mp4` holds the camera still and moves
    through time, which is the only way growth reads as growth (a per-frame autofit rescaled the
    box 4.6x over a run and hid it). `kburns.mp4` holds time still at the last frame and moves the
    camera, which is the only way an arm pointing at the lens reads as an arm. A card that plays
    one of them is missing the other, and side by side they are two small movies; in sequence they
    are the run and then its specimen, at one size.

    BOTH HALVES ARE CROPPED OFF THEIR OWN TEXT. The Ken Burns render stamps the run name and a
    scale bar -- correct for a figure, wrong for a card whose caption the page writes -- so it is
    cropped square about its content between the same margins the evolve half uses.

    ONE SIZE is the difficulty `concat` imposes: the Ken Burns half is scaled to whatever square
    the evolve half measured, so the tissue stays the size the rest of the row draws it.
    """
    import shutil as _sh
    import tempfile
    mv = os.path.join(run_dir, "movie.mp4")
    kb = os.path.join(run_dir, "kburns.mp4")
    name = os.path.basename(run_dir)
    ready = os.path.exists(kb)
    if ready:
        try:
            _nframes(kb)
        except Exception:
            ready = False
    if not ready:
        print(f"[minisite] {name}: kburns.mp4 missing or still being written -- evolve only")
        crop_panel(mv, dst, panel=panel, pad=pad, skip_top=skip_top, skip_bot=skip_bot)
        return False
    d = tempfile.mkdtemp(prefix="evkb_")
    a, b = os.path.join(d, "a.mp4"), os.path.join(d, "b.mp4")
    crop_panel(mv, a, panel=panel, pad=pad, skip_top=skip_top, skip_bot=skip_bot)
    # MEASURED, NOT GUESSED: in a 770-px Ken Burns frame the run label occupies rows 104-119 and
    # the scale bar 629-654, so the window has to start below 0.156 of the height and end above
    # 0.185 from the bottom. The first pass used 0.08/0.12 and kept the label.
    panels_concat(kb, b, [(0, 0, 1.0, 1.0)], skip_top=0.157, skip_bot=0.186, pad=1.02)
    side = _size(a)[0]
    na, nb = _nframes(a), _nframes(b)
    ff = _exe("ffmpeg")
    # `setsar=1` and one fps on both: concat refuses streams that disagree on either, and the two
    # renderers never had to agree.
    fc = (f"[0:v]fps=20,scale={side}:{side},setsar=1[a];"
          f"[1:v]fps=20,scale={side}:{side},setsar=1[b];[a][b]concat=n=2:v=1[o]")
    cmd = [ff, "-y", "-loglevel", "error", "-i", a, "-i", b, "-filter_complex", fc,
           "-map", "[o]", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "24", dst]
    ok = subprocess.call(cmd) == 0 and os.path.exists(dst)
    _sh.rmtree(d, ignore_errors=True)
    if not ok:
        sys.exit(f"ffmpeg evolve+kburns concat failed for {dst}")
    print(f"[minisite]   {name}: evolve {na} frames + ken burns {nb}, {side}x{side}")
    return True


def crop_panel(src, dst, panel="left", skip_top=0.09, skip_bot=0.14, pad=1.20):
    """Keep the LEFT panel only, as a square window centred on what is drawn in it.

    THE MOVIE IS A CONTACT SHEET, NOT A CLIP. `log/okuda/*/movie.mp4` is drawn for reading a run:
    two views side by side, each labelled with its elevation, each with a scale bar, and a section
    inset in the corner. A gallery card is one square block, so the page takes one panel -- the side
    view -- and the crop has to be measured rather than guessed, because the tissue GROWS: a window
    fitted to the first frame cuts the last one off.

    `skip_top` / `skip_bot` are the fractions of the panel its printed text occupies -- the "side
    elev 18" label above and the scale bar below. Measured between them, the box is the tissue's;
    the window is then clamped to stay inside those margins, so no frame of the result carries a
    caption the page has not written itself.

    `panel="right"` takes the top view instead, for a run whose interesting face is on top. THE BOX
    IS STILL MEASURED ON THE LEFT PANEL, and deliberately: the right one carries the section-ring
    inset in its bottom corner, which is bright, is not the tissue, and drags any box measured
    around it out to the frame edge. Both panels draw the same tissue at the same axes scale and
    the same centre, so the left panel's window is the right one's window plus the offset.
    """
    ff = _exe("ffmpeg")
    w, h = _size(src)
    half = (w // 2) - (w // 2) % 2
    top, bot = int(skip_top * h), int(skip_bot * h)
    cx, cy, sz = _content_box(src, 0, half, h, skip_top=skip_top, skip_bot=skip_bot)
    cy += top
    side = min(half, h - top - bot, int(pad * sz))
    side -= side % 2
    x = min(max(cx - side // 2, 0), half - side)
    y = min(max(cy - side // 2, top), h - bot - side)
    if panel == "right":
        x += w - half
    print(f"[minisite]   panel crop: {side}x{side} at ({x},{y}) of {w}x{h}", flush=True)
    cmd = [ff, "-y", "-loglevel", "error", "-i", src, "-vf", f"crop={side}:{side}:{x}:{y}",
           "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "20", dst]
    if subprocess.call(cmd) != 0 or not os.path.exists(dst):
        sys.exit(f"ffmpeg panel crop failed for {dst}")


def _exe(name):
    """Next to the interpreter, not on PATH -- the conda env ships ffmpeg but the shell does not see it."""
    p = os.path.join(os.path.dirname(sys.executable), name)
    if os.path.exists(p):
        return p
    import shutil as _sh
    return _sh.which(name) or name


def _size(path):
    out = subprocess.check_output([_exe("ffprobe"), "-v", "error", "-select_streams", "v",
                                   "-show_entries", "stream=width,height",
                                   "-of", "csv=p=0", path]).decode().strip()
    w, h = (int(v) for v in out.split(",")[:2])
    return w, h


def card(video, name, spec_path, cap):
    spec = html.escape(open(spec_path).read().rstrip(), quote=False).replace("'", "&#x27;")
    return f"""  <figure class="sim-card">
    <video src="gallery/{video}" autoplay loop muted playsinline preload="metadata"></video>
    <figcaption>
      <span class="sim-name" tabindex="0">{name}<span class="sim-spec"><pre>{spec}</pre></span></span>
      <span class="sim-cap">{cap}</span>
    </figcaption>
  </figure>"""



def replace_card(video, name, spec_path, cap, files=(), new_video=None):
    """Rewrite ONE hand-written gallery card in place, matched on the clip it plays.

    The generated block below owns the Vertex + MPM section; the cards in the older sections are
    part of the page's own prose and are not in it. Rewriting one by hand would break the same rule
    this file exists to enforce -- that a card's spec is READ from the run that produced it rather
    than pasted -- so it is done here, keyed on the video filename, which is the one thing about a
    card that does not change when its content does.
    """
    # THE CLIP A CARD PLAYS AND THE CLIP IT IS FOUND BY ARE NOT THE SAME QUESTION. Two cards on
    # this page play `tyssue_grow_divide.mp4` -- the vertex model's own, and the growth phase of the
    # Turing section -- so overwriting that FILE changes both, and the second one's spec then
    # describes a run its clip no longer shows. A new card gets a new filename and only the card
    # named here is repointed.
    blk = card(new_video or video, name, spec_path, cap)
    for path, rendered in files:
        if not os.path.exists(path):
            continue
        s = open(path).read()
        i = s.find(f'<video src="gallery/{video}"')
        if i < 0:
            print(f"[minisite] {os.path.basename(path)}: no card plays {video} -- not replaced")
            continue
        # `<figure` AND NOT `<figure class="sim-card">`. Quarto renders the class list as
        # `sim-card figure`, so matching the bare class found nothing in the rendered page, `rfind`
        # returned -1, and the "replacement" was appended at the END OF THE FILE -- a second card
        # four thousand lines below the gallery it belongs to, with the original still in place.
        a = s.rfind("<figure", 0, i)
        b = s.index("</figure>", i) + len("</figure>")
        out = blk if not rendered else blk.replace("&#x27;", "'")
        open(path, "w").write(s[:a] + out.lstrip() + s[b:])
        print(f"[minisite] {os.path.basename(path)}: card for {video} replaced ({name})")


