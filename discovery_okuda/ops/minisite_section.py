def _measured(run):
    """The run's own `metrics.json`, so a number in a caption is a number the run reported.

    The same rule as the specs: the page quotes runs, and a quantity typed by hand is one that stops
    being true the next time the run changes without anybody noticing.
    """
    return json.load(open(os.path.join(LOG, run, "metrics.json")))


