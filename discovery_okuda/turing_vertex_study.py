#!/usr/bin/env python
"""turing_vertex_study -- the discovery loop pointed at the Turing x vertex settings.

WHAT THIS IS FOR
------------------------------------------------------------------------------------------------
The minisite's "Turing x vertex" section shows two movies, both generated by
`prototype/Tyssue/archive_rounded.py`: a plain grow+divide vesicle and a Gray-Scott "coral" one.
Reproducing them (2026-07-30) turned up something that changes what is worth asking:

    THE TWO MOVIES ARE THE SAME SIMULATION.

Their archived diagnostics are identical -- cells_end 1778, vol_cv 0.226, hollow_frac 0.004 -- and
the reproduction confirms it. The growth law in `morphogen_growth_3d` is

        hillv = a^h / (a_sw^h + a^h)                    # in [0, 1]
        s    <- s * (1 + rate * (rho + hillv))          # per-cell cumulative volume scale
        if rho > 0:  s <- min(s, (vth_frac * v_ref / V0f_init)^(1/3))     # <-- THE CAP
        else:        s <- min(s, cap)

and the archived settings are `a_sw = 50.0, rho = 1.0`. TWO separate things then make the
chemistry decorative, and only one of them is the obvious one:

  1. `a_sw = 50` with a Gray-Scott activator around 0.4 gives `hillv ~ 4e-9`. The switch never
     fires. This is the obvious one, and it is the one you would try to fix first.
  2. `rho > 0` selects the **capped** branch, which pins EVERY cell to the same target volume
     `vth_frac * v_ref`. Under that cap a high-activator cell does not grow BIGGER, it merely
     reaches the division threshold SOONER. Shape is activator-independent BY CONSTRUCTION.

So (2) predicts that fixing (1) alone changes nothing about the shape. That is the first
hypothesis this study records and tests, and it is one I can be wrong about.

That is a fine thing for a gallery and a bad thing to reason from, because it means the site does
not yet show Turing chemistry SHAPING anything. So the question this study asks is not "does it
run" but:

    ACROSS THE (a_sw, rho, chi, rate) SETTINGS, WHEN DOES THE PATTERN STOP COLOURING AND START
    DRIVING THE SHAPE -- AND WHAT DOES IT MAKE WHEN IT DOES?

THE 1778 DEFECT (2026-07-31) -- READ THIS BEFORE TRUSTING ANY CELL COUNT HERE
------------------------------------------------------------------------------------------------
Every one of the first 32 runs ended at `cells_end = 1778`. Not biology -- arithmetic:

    build() sized the vertex reservoir as int(Nv * 12) with Nv the INITIAL vertex count.
    A closed trivalent sheet has V = 2F - 4, so n_cells=150 -> Nv=296 -> reservoir 3552.
    divide_3d refuses a split once `len(pos) + 2 > buf`, so the reservoir is a HARD face cap:
        F_max = (3552 + 4) // 2 = 1778.

Every run drove into that wall and stopped there. A sweep whose points all end at the same
buffer ceiling is a measurement of the buffer. The fixes, all three of them:

  * `n_cells` is a first-class knob (`--n-cells`, `--sweep n_cells`, `--okuda`). Okuda's cases
    start at 200 / 2000 / 4000 cells; we were running 150, so we were not running his system.
  * the reservoir is sized for WHERE THE RUN IS GOING (`growth_headroom`, or an absolute
    `max_cells`), never for where it started -- see `reservoir_plan`. The cap is now a number
    somebody chose and the record prints it.
  * a run that ENDS AT the cap is marked `saturated` and `valid_evidence: false`, exactly as the
    main loop does (critic.P2_BUFFER_SATURATED / run_one.py's saturation guard). The study never
    checked; that is why the wall went unnoticed for 32 runs.

`python turing_vertex_study.py --caps` prints the legacy vs planned cap for the standard sizes,
and `--selfcheck` runs the whole guard end to end (short runs, no sweep).

THE ONE-VIEWPOINT DEFECT (2026-07-31) -- READ THIS BEFORE TRUSTING ANY PICTURE FROM HERE
------------------------------------------------------------------------------------------------
`_render` drew every 3D panel from ONE elevation. `_draw`'s last statement is
`view_init(elev=18, azim=azim)`, the strip asked for `azim=30` four times, and the movie spun the
azimuth at that same elevation. Measured on the pre-fix code: strip = 1 distinct (elev, azim),
movie = 25 azimuths but 1 elevation. A protrusion growing along the camera's line of sight is
then pure foreshortening -- rendered with a synthetic tube aimed at the side camera, the old
strip's silhouette elongation went 1.004 -> 1.014, i.e. the tube was invisible; from the added
near-polar view the same tube reads 1.003 -> 1.557. Every panel now carries SIDE and TOP
(CAM_SIDE / CAM_TOP, matching run_one.py), and `_cam_assert` refuses a one-elevation artefact.
The box was already computed once for the whole run and is NOT part of this defect -- it was
checked, and it is re-read off the axes every draw so it stays that way.

THE MEASUREMENT THAT DECIDES IT
------------------------------------------------------------------------------------------------
`corr_act_rad` -- the Pearson correlation between a cell's activator and its radius. It is the
only metric here that can tell colouring from driving:

    ~0.0   the bulges are wherever they were going to be; the chemistry is decorative
    >0.3   cells bulge WHERE the activator is; the pattern is shaping the sheet

The prior campaign (Turing_vertex, spherical SPV backend) reached corr 0.42 at best and recorded
that "localized growth does NOT produce localized extrusion" on shell mechanics with corr ~ 0.03.
Those numbers are the yardstick; this study measures the same quantity on the vertex-mesh backend,
which is the one the talk is about.

DISCIPLINE (the same as the main loop, deliberately)
------------------------------------------------------------------------------------------------
Every point carries a PREDICTION recorded before it runs, scored by `predict.score` -- so an
unparseable or unmet prediction cannot quietly become a confirmation, and the surprise rate means
something. Runs are CPU subprocesses (the box has 64 cores); a wave of 6 x 400 frames takes a few
minutes, which is what makes a real hypothesis-first loop affordable here at all.

    python turing_vertex_study.py --sweep a_sw --values 50,0.6,0.45,0.30,0.15 --frames 400
    python turing_vertex_study.py --sweep a_sw --values 0.3 --n-cells 2000          # Okuda's size
    python turing_vertex_study.py --okuda --frames 400                              # 200/2000/4000
    python turing_vertex_study.py --one '{"name":"x","a_sw":0.3}' --frames 400      # worker
    python turing_vertex_study.py --caps                                            # the cap table
    python turing_vertex_study.py --selfcheck                                       # the guards
"""
