def cell_adjacency_pairs(mt):
    """(faceA, faceB) for every pair of cells sharing a mesh edge -- the RD graph itself.

    Rebuilt from the SAME half-edge table `tyssue_rd_ops.CellAdjacency` uses, so a spot is
    counted on exactly the graph the diffusion ran on, not on a geometric stand-in for it.
    """
    import numpy as np
    es = np.asarray(mt["E_srce"], dtype=np.int64).ravel()
    et = np.asarray(mt["E_trgt"], dtype=np.int64).ravel()
    ef = np.asarray(mt["E_face"], dtype=np.int64).ravel()
    if es.size == 0:
        return np.zeros(0, np.int64), np.zeros(0, np.int64)
    lo, hi = np.minimum(es, et), np.maximum(es, et)
    key = lo.astype(np.int64) * (int(hi.max()) + 1) + hi        # undirected edge id
    o = np.argsort(key, kind="stable")
    ks, fs = key[o], ef[o]
    j = np.flatnonzero(ks[:-1] == ks[1:])                       # a manifold edge appears twice
    A, B = fs[j], fs[j + 1]
    keep = A != B
    return A[keep], B[keep]


def count_spots(mt, act, live, frac=0.5):
    """How many DISTINCT chemical spots? (connected components of cells above frac x peak.)

    Cheap, and the quantity Okuda calibrates against (~5 spots at 2000 cells). Deliberately the
    same threshold `act_frac_high` already uses, so the two numbers describe one set of cells:
    `act_frac_high` says how MUCH is lit, `n_spots` says in how many PIECES.

    Reported honestly: a flat/zero activator has no spots to count and returns None, not 0 --
    "no pattern" and "one spot covering everything" are different findings. Singleton components
    are counted (a one-cell spot is a spot), so `n_spots_ge3` is carried alongside for readers
    who want the noise-insensitive version.

    WHAT IT IS NOT: an early-frame count is a count of the SEEDS, not of spots. cell_rd_seed
    scatters `seed_frac` of the cells, so a 10-frame run at n_cells=2000 reports ~78 one- and
    two-cell components -- correct, and nothing to do with Okuda's ~5 MATURE spots. Compare
    against Okuda only after the pattern has coarsened, and read `spot_sizes_top` next to it.
    """
    import numpy as np
    from scipy.sparse import coo_matrix
    from scipy.sparse.csgraph import connected_components

    a = np.asarray(act, dtype=float)
    a = np.where(np.isfinite(a), a, 0.0)
    lv = np.asarray(live, dtype=bool)
    if lv.sum() < 2:
        return {"n_spots": None, "spots_undefined_why": "fewer than 2 live cells"}
    amax = float(a[lv].max())
    if amax <= 1e-9:
        return {"n_spots": None, "spots_undefined_why": "activator is zero everywhere"}
    hot = lv & (a > frac * amax)
    n = int(hot.sum())
    if n == 0:
        return {"n_spots": 0, "spot_cells": 0, "spot_thresh": round(frac * amax, 6)}
    A, B = cell_adjacency_pairs(mt)
    idx = np.flatnonzero(hot)
    remap = np.full(a.shape[0], -1, np.int64)
    remap[idx] = np.arange(n)
    m = (A < a.shape[0]) & (B < a.shape[0])
    A, B = A[m], B[m]
    m = hot[A] & hot[B]                                          # keep only hot-hot links
    ga, gb = remap[A[m]], remap[B[m]]
    g = coo_matrix((np.ones(ga.size), (ga, gb)), shape=(n, n))
    ncomp, lab = connected_components(g, directed=False)
    sizes = np.sort(np.bincount(lab, minlength=ncomp))[::-1]
    return {"n_spots": int(ncomp), "n_spots_ge3": int((sizes >= 3).sum()),
            "spot_cells": n, "spot_frac": round(n / float(lv.sum()), 4),
            "spot_sizes_top": [int(s) for s in sizes[:8]],
            "spot_thresh": round(frac * amax, 6)}


def metrics(mt, pos, act):
    """Geometry + pattern + THE COUPLING. Returns a flat dict of floats."""
    import numpy as np
    import torch
    from tyssue_ops3d import face_geometry_3d
    from tyssue_diag import hollow_flags

    nF = int(mt["nF"])
    area, perim, cen, vf = face_geometry_3d(
        torch.as_tensor(pos), torch.as_tensor(np.asarray(mt["E_srce"])),
        torch.as_tensor(np.asarray(mt["E_trgt"])), torch.as_tensor(np.asarray(mt["E_face"])), nF)
    cen = cen.numpy()[:nF]
    vfn = vf.numpy()
    live = np.abs(vfn) > 1e-9
    r = np.linalg.norm(cen, axis=1)
    a = np.asarray(act[:nF], dtype=float)
    ok = live & np.isfinite(r) & np.isfinite(a)
    r, a = r[ok], a[ok]
    m = {"cells_end": int(nF), "n_live": int(ok.sum())}
    if r.size < 8:
        return {**m, "degenerate": True}
    rmed = float(np.median(r))
    m.update(
        vol_cv=float(np.std(vfn[live]) / (abs(np.mean(vfn[live])) + 1e-9)),
        hollow_frac=float(hollow_flags(pos, mt)[2]["frac"]),
        r_med=rmed, r_cv=float(r.std() / (rmed + 1e-9)),
        # protrusion: how far the furthest cell sticks out beyond the body
        protr=float(r.max() / (rmed + 1e-9)),
        protr_p99=float(np.percentile(r, 99) / (rmed + 1e-9)),
        act_mean=float(a.mean()), act_max=float(a.max()),
        act_frac_high=float((a > 0.5 * a.max()).mean()) if a.max() > 1e-9 else 0.0,
        act_nan=bool(not np.isfinite(np.asarray(act[:nF], dtype=float)).all()),
    )
    # how many DISTINCT spots (Okuda: ~5 at 2000 cells). Full-length arrays -- the counter works
    # on face indices, not on the `ok`-compressed subset.
    m.update(count_spots(mt, np.asarray(act[:nF], dtype=float), live))
    # ---- THE metric: does the shape follow the pattern, or merely wear it? ----
    if a.std() > 1e-9 and r.std() > 1e-9:
        m["corr_act_rad"] = float(np.corrcoef(a, r)[0, 1])
    else:
        # a flat activator field cannot correlate with anything. Report it as absent, NOT as 0.0:
        # 0.0 would read as "measured, no coupling" when the truth is "no pattern to couple".
        m["corr_act_rad"] = None
        m["corr_undefined_why"] = ("activator is uniform" if a.std() <= 1e-9
                                   else "radius is uniform")
    return m


def run_one(k, frames, movie=False):
    """Run one setting to completion and return its metrics. Called in a subprocess."""
    import numpy as np
    from plexus.engine import run as engine_run

    t0 = time.time()
    sim, cfg, mesh0 = build(k, frames)
    plan = mesh0["plan"]
    d = os.path.join(OUT, k["name"])
    os.makedirs(d, exist_ok=True)
    rec = {"name": k["name"], "knobs": {x: k[x] for x in k if x != "name"}, "frames": frames,
           "plan": plan}
    # a run that STARTS at 95% of its cap has nowhere to go and will trip the guard on frame 1;
    # say so before the hours are spent, not after.
    tight = "  ⚠ TIGHT: the run starts near its own cap" if plan["growth_headroom"] < 1.2 else ""
    print(f"[{k['name']}] start {plan['n_cells']} cells -> face cap {plan['face_cap']} "
          f"(headroom {plan['growth_headroom']}x, vertex reservoir {plan['vbuf']}){tight}",
          flush=True)
    try:
        Hf, out = engine_run(sim, device="cpu")
        emesh = Hf.level("vertex")._mesh
        hist = emesh.get("hist")
        posf = out["sets"]["vertex"]["pos"]
        chemf = out["sets"]["cell"]["state"]["chem"]
        T = posf.shape[0]
        # THE PHANTOM GUARD. `hist[min(t, len(hist)-1)]` is the line that produced the phantom
        # "97% hollow / global buckling" result: it pairs frame t's coordinates with ANOTHER
        # frame's connectivity and fabricates inverted cells. run_one.py:check_alignment was
        # written to forbid exactly this, and this module -- which produced every hollow_frac
        # behind OR001 -- never called it. Assert, never clamp.
        from run_one import check_alignment
        check_alignment(posf, hist, name=k["name"])
        mtT = hist[T - 1]
        pT = posf[T - 1][:mtT["Nv"]].astype(np.float64)
        aT = chemf[T - 1][:mtT["nF"], 0]
        rec.update(metrics(mtT, pT, aT))
        # a mid-run reading too: a setting that blows up late still says something
        tm = T // 2
        mtm = hist[tm]
        rec["mid"] = metrics(mtm, posf[tm][:mtm["Nv"]].astype(np.float64),
                             chemf[tm][:mtm["nF"], 0])
        if movie:
            _render(d, k, hist, posf, chemf, T, mesh0)
        # ------------------------------------------------------------ THE SATURATION GUARD
        # 32 runs ended at exactly 1778 cells and this study reported every one of them as a
        # measurement. A run that ends AT its face cap is evidence about the reservoir; the main
        # loop already refuses such runs (critic.P2_BUFFER_SATURATED), so this one does too.
        rec.update(saturation_report(rec.get("cells_end", 0), mtT["Nv"], plan))
        rec["ok"] = True
    except Exception as e:
        import traceback
        rec.update(ok=False, error=repr(e))
        traceback.print_exc()
    rec["valid_evidence"] = bool(rec.get("ok") and not rec.get("saturated"))
    rec["secs"] = round(time.time() - t0, 1)
    if rec.get("saturated"):
        # first key in the file, and a line in the log nobody can scroll past
        rec = {"NOT_EVIDENCE": rec.pop("NOT_EVIDENCE"), **rec}
        print(f"\n[{k['name']}] {'=' * 78}\n[{k['name']}] 🔴 {rec['NOT_EVIDENCE']}\n"
              f"[{k['name']}] {'=' * 78}\n", flush=True)
    json.dump(rec, open(os.path.join(d, "diag.json"), "w"), indent=1)
    return rec


def _render(d, k, hist, posf, chemf, T, mesh0):
    """Strip + movie, coloured BY ACTIVATOR, drawn from TWO viewpoints (see CAM_SIDE/CAM_TOP).

    Rows/panels are SIDE (elev 18) and TOP (elev 88) plus the cross-section. One viewpoint was
    enough to hide a tube growing along the camera axis -- the phenotype `corr_act_rad` exists to
    score -- so both artefacts now carry both. Both viewpoints share the one fixed box, so they
    are directly comparable to each other and across frames.
    """
    import numpy as np
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.animation import FFMpegWriter
    try:
        import imageio_ffmpeg
        matplotlib.rcParams["animation.ffmpeg_path"] = imageio_ffmpeg.get_ffmpeg_exe()
    except Exception:
        pass
    # make_movie_axes/draw_movie_frame are deliberately NOT used any more: they only build the
    # ONE-panel layout, which is the defect. The movie figure is laid out here, as run_one does.
    from run_tyssue_vesicle import _draw, _draw_cross

    from run_one import check_alignment
    check_alignment(posf, hist, name=k["name"] + " (render)")   # the phantom guard, render path

    def frame(t):
        mt = hist[t]
        return mt, posf[t][:mt["Nv"]].astype(np.float64), chemf[t][:mt["nF"], 0]

    aT = frame(T - 1)[2]
    lo, hi = float(np.percentile(aT, 5)), float(np.percentile(aT, 99) + 1e-6)
    col = lambda mt, pt, a: np.clip((a - lo) / (hi - lo + 1e-9), 0, 1)     # noqa: E731
    # ONE box for the whole run (max over sampled frames, not per-frame autofit): run_one.run_box
    # documents why -- a re-fitted frame renders an inflating sphere at constant apparent size and
    # hides growth. Unchanged here; `used_box` below re-reads it off the axes to keep it honest.
    Rmax = max(float(np.linalg.norm(frame(t)[1], axis=1).max())
               for t in np.linspace(0, T - 1, 20).astype(int))
    L3, L2 = Rmax * 1.06, Rmax * 2.23

    # What was ACTUALLY rendered, read back off the axes after each draw -- not what we meant to
    # set. This is the instrument that catches the failure mode below (re-aiming too early), and
    # it is what the `2 elevations` assertion is checked against.
    used, used_box = set(), set()

    def draw3d(ax, pt, mt, c, cam, azim=None):
        az = cam["azim"] if azim is None else azim
        _draw(ax, pt, mt, k["p0"], azim=az, act=c, Lbox=L3)
        # _draw's LAST statement is view_init(elev=18, azim=azim). Re-aiming BEFORE the call is
        # a silent no-op that collapses TOP back onto SIDE, so the re-aim must come AFTER it.
        ax.view_init(elev=cam["elev"], azim=az)
        used.add((round(float(ax.elev)), round(float(ax.azim))))
        used_box.add(round(float(ax.get_xlim()[1]), 6))

    # strip: three rows -- 3D side, 3D near-polar, cross-section
    fig = plt.figure(figsize=(17.6, 13.5))
    fig.patch.set_facecolor("black")
    for i, t in enumerate([int(round(f * (T - 1))) for f in (0.0, 0.33, 0.66, 1.0)]):
        mt, pt, a = frame(t)
        c = col(mt, pt, a)
        draw3d(fig.add_subplot(3, 4, i + 1, projection="3d"), pt, mt, c, CAM_SIDE)
        draw3d(fig.add_subplot(3, 4, 4 + i + 1, projection="3d"), pt, mt, c, CAM_TOP)
        _draw_cross(fig.add_subplot(3, 4, 8 + i + 1), pt, mt, k["p0"], act=c, Lbox=L2)
    fig.subplots_adjust(0.006, 0.005, 0.996, 0.996, wspace=0.02, hspace=0.02)
    fig.savefig(os.path.join(d, "strip.png"), dpi=110, facecolor="black")
    plt.close(fig)
    _cam_assert(used, used_box, k["name"], "strip")

    # movie: the two 3D viewpoints side by side + the cross-section inset (bottom-right)
    figm = plt.figure(figsize=(10.0, 5.2))
    figm.patch.set_facecolor("black")
    axs = figm.add_subplot(1, 2, 1, projection="3d")
    axt = figm.add_subplot(1, 2, 2, projection="3d")
    figm.subplots_adjust(0, 0, 1, 1, wspace=0.0)
    axin = figm.add_axes([0.83, 0.0, 0.17, 0.34])
    axin.set_facecolor("none")
    axin.patch.set_alpha(0.0)
    used.clear()
    used_box.clear()
    keep = np.arange(0, T, max(1, T // 150))
    wri = FFMpegWriter(fps=12, metadata={"title": k["name"]})
    with wri.saving(figm, os.path.join(d, "movie.mp4"), dpi=110):
        for j, t in enumerate(keep):
            mt, pt, a = frame(int(t))
            c = col(mt, pt, a)
            az = (2 * j) % 360        # the turntable is kept, and SHARED by both panels so the
            #                           two views stay registered frame by frame; what makes them
            #                           independent viewpoints is the 70 deg of elevation.
            draw3d(axs, pt, mt, c, CAM_SIDE, azim=az)
            draw3d(axt, pt, mt, c, CAM_TOP, azim=az)
            # _draw calls ax.clear(), which drops the label -- re-stamp it every frame.
            axs.text2D(0.02, 0.96, f"side  elev {CAM_SIDE['elev']}", transform=axs.transAxes,
                       color="w", fontsize=9)
            axt.text2D(0.02, 0.96, f"top  elev {CAM_TOP['elev']}", transform=axt.transAxes,
                       color="w", fontsize=9)
            _draw_cross(axin, pt, mt, k["p0"], act=c, Lbox=L2, axis=1)
            axin.axis("off")
            wri.grab_frame()
    plt.close(figm)
    _cam_assert(used, used_box, k["name"], "movie")


def _cam_assert(used, used_box, name, what):
    """Report the cameras+box READ BACK off the axes, and refuse a one-viewpoint artefact.

    Loud, not silent: the single-viewpoint defect survived because nothing ever stated how many
    viewpoints an artefact carried, so a renderer that quietly drew one looked exactly like a
    renderer that drew two. A regression here fails the run (run_one catches, ok=False) instead
    of shipping a picture that cannot show the phenotype.
    """
    elevs = sorted({e for e, _ in used})
    boxes = sorted(used_box)
    verdict = ("FIXED for every frame and both views" if len(boxes) == 1
               else f"{len(boxes)} DIFFERENT boxes -- the frame moved between draws")
    print(f"[{name}] {what} camera: {len(used)} (elev,azim) pairs rendered, elevations {elevs}, "
          f"box half-width {boxes}: {verdict}", flush=True)
    assert len(elevs) >= 2, (f"{what}: SINGLE-VIEWPOINT DEFECT -- only elevations {elevs} were "
                             f"rendered; a tube along the camera axis can hide in this artefact")
    assert len(used_box) == 1, (f"{what}: the axis box moved between frames ({sorted(used_box)}) "
                                f"-- per-frame autofit hides growth")


