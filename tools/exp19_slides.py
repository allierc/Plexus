def _json(run, kind):
    p = os.path.join(LOG, run, "results", f"{run}_{kind}.json")
    return json.load(open(p)) if os.path.exists(p) else None


def _ax_style(ax):
    ax.set_facecolor("black")
    for sd in ("top", "right"):
        ax.spines[sd].set_visible(False)
    for sd in ("left", "bottom"):
        ax.spines[sd].set_color("0.6")
    ax.tick_params(colors="0.8", labelsize=9)


def fig_levers(b, arms, path):
    """Brain-mean R2 (exp17's headline) and R2 against the denoised recording of each arm's free rollout; black,
    labels above (exp17's batch figure). One axis on every batch slide; a value off it is written at the edge."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axs = plt.subplots(1, 2, figsize=(9, 3.6), facecolor="black", sharey=True)
    y = np.arange(len(arms))[::-1]
    lim = (-1.5, 1.0)
    for ax, key, lab in ((axs[0], "brain_mean_r2", "a   brain-mean R$^2$ (fish-mean trace)"),
                         (axs[1], "r2_denoised", "b   R$^2$, denoised recording, every voxel")):
        _ax_style(ax)
        ax.axvline(0, color="0.6", lw=1.0)
        for yy, (lab_a, run) in zip(y, arms):
            ab = _json(run, "ablation")
            v = ab["full"][key] if ab else None
            if v is None:
                ax.text(0.01, yy, "held out: next slides", color="0.5", va="center", fontsize=8,
                        transform=ax.get_yaxis_transform())
                continue
            ax.barh(yy, float(np.clip(v, *lim)), color="#1f77b4", height=0.6)
            txt = f"{v:+.3f}" if lim[0] <= v <= lim[1] else f"{v:+.3g} (off axis)"
            ax.text(float(np.clip(v, *lim)) + (0.03 if v >= 0 else -0.03), yy, txt, color="white", va="center",
                    ha="left" if v >= 0 else "right", fontsize=8)
        ax.set_xlim(*lim)
        ax.set_title(lab, color="white", loc="left", fontsize=11)
        ax.set_xlabel("higher is better; 0 = a constant at the recording's mean", color="0.8", fontsize=8)
    axs[0].set_yticks(y)
    axs[0].set_yticklabels([f"{a}   {i + 1}" for i, (a, _) in enumerate(arms)], color="white", fontsize=9)
    fig.tight_layout()
    fig.savefig(path, dpi=160, facecolor="black")
    plt.close(fig)


def fig_controls(rows, path, title):
    """The fish-mean trace (raw F / F0, the voxels on the mask) over the free rollout: recorded, and each control."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(9, 3.4), facecolor="black")
    _ax_style(ax)
    rec = None
    for label, run, key, col in rows:
        z = os.path.join(LOG, run, "results", f"{run}_ablation.npz")
        if not os.path.exists(z):
            continue
        d = np.load(z)
        if rec is None:
            rec = d["fish_mean_recorded"]
            t = np.arange(len(rec)) * 3.81 / 3600
            ax.plot(t, rec, color="white", lw=0.8, label="recorded")
        if key in d.files:
            ax.plot(t, d[key], color=col, lw=1.0, label=label)
    ax.set_xlabel("hours after volume 4", color="0.8", fontsize=9)
    ax.set_title(title, color="white", loc="left", fontsize=11)
    ax.legend(facecolor="black", edgecolor="0.4", labelcolor="white", fontsize=8, loc="upper left")
    fig.tight_layout()
    fig.savefig(path, dpi=160, facecolor="black")
    plt.close(fig)


def fig_heldout(path):
    """wl_gc_base's skill at h 1..10 against each voxel's best recent mean (the target's baseline), beside persistence,
    the best space-time blur, and the noise ceiling (data/baselines.json)."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    hz = _json("wl_gc_base", "horizons")
    base = json.load(open(os.path.join(EXP, "data", "baselines.json")))["gcamp"]["h"]
    hs = sorted(int(h) for h in hz["h"])
    sk = [1 - hz["h"][str(h)]["mse"] / base[str(h)]["baseline_mse"] for h in hs]
    fig, ax = plt.subplots(figsize=(7.5, 3.6), facecolor="black")
    _ax_style(ax)
    ax.axhline(0, color="0.6", lw=1.0)
    ax.plot(hs, [base[str(h)]["ceiling_skill"] for h in hs], color="0.6", ls="--", lw=1.0, label="noise ceiling")
    ax.plot(hs, [base[str(h)]["persistence_skill"] for h in hs], color="#ff7f0e", lw=1.0, label="persistence")
    ax.plot(hs, [base[str(h)]["space_time_skill"] for h in hs], color="#9467bd", lw=1.0, label="space-time blur")
    ax.plot(hs, sk, color="#1f77b4", lw=2.0, marker="o", ms=4, label="GraphCast law (wl_gc_base)")
    ax.set_xlabel("volumes ahead (1 volume = 3.81 s)", color="0.8", fontsize=9)
    ax.set_title("skill = 1 - MSE / MSE of each voxel's best recent mean (held-out last 20 %)", color="white", loc="left", fontsize=10)
    ax.legend(facecolor="black", edgecolor="0.4", labelcolor="white", fontsize=8, loc="lower left")
    fig.tight_layout()
    fig.savefig(path, dpi=160, facecolor="black")
    plt.close(fig)
    return hs, sk


