def tex(s):
    """LaTeX-safe text; the unit `um` (a whole word only) becomes the micro sign."""
    return re.sub(r"\bum\b", r"\\textmu m", str(s).replace("\\", "/").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
            .replace("#", "\\#"))


def rows(pairs):
    return ("{\\scriptsize\\begin{tabular}{@{}l@{\\hspace{7pt}}l@{}}\n"
            + "".join(f"{tex(a)} & {tex(b)} \\\\\n" for a, b in pairs) + "\\end{tabular}\\par}")


def frame(name, source, left, right):
    body = (f"% generated by tools/exp19_slides.py from {source}\n"
            f"\\begin{{frame}}[t]{{{TITLE}}}\n\\vspace*{{\\bandgap}}\n"
            "\\begin{columns}[T,onlytextwidth]\n\\begin{column}{0.58\\textwidth}\n"
            # the picture centred in the slide's height: a box as tall as the right column may be, its content
            # vertically centred ([c]), its top on the columns' top ([t]) so nothing climbs into the title band
            f"\\begin{{minipage}}[t][\\colheight][c]{{\\linewidth}}\n{left}\n\\end{{minipage}}\n\\end{{column}}\n\\begin{{column}}{{0.4\\textwidth}}\n\\vspace*{{2\\baselineskip}}\n"
            f"\\fitcol{{%\n{right}\n}}\n\\end{{column}}\n\\end{{columns}}\n\\end{{frame}}\n")
    open(os.path.join(PRES, "slides", f"{name}.tex"), "w").write(body)
    return name


def head(s):
    return f"{{\\normalsize\\textbf{{{tex(s)}}}}}\\\\[4pt]"


